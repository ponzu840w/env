#!/bin/bash
# mac 用の設定を展開する。配置先にはリポジトリ本体を読み込むstubを生成する
# 何度実行しても同じ結果になる（冪等）。管理外のファイルがあれば何も変更せず中止する
# 使い方: mac/install.sh [--dry-run]
set -euo pipefail

DRY_RUN=""
[ "${1:-}" = "--dry-run" ] && DRY_RUN=1
REPO="$(cd "$(dirname "$0")/.." && pwd -P)"  # シンボリックリンクを解決した実パス
MARKER='generated by env/mac/install.sh'

vim_stub()  { printf '" %s\nscriptencoding utf-8\nsource %s\n' "$MARKER" "${REPO// /\\ }/$1"; }
sh_stub()   { printf '# %s\n. '\''%s'\''\n' "$MARKER" "$REPO/$1"; }
pwsh_stub() { printf '# %s\n. '\''%s'\''\n' "$MARKER" "$REPO/$1"; }
tmux_stub() { printf '# %s\nsource-file '\''%s'\''\n' "$MARKER" "$REPO/$1"; }
rl_stub()   { printf '# %s\n$include %s\n' "$MARKER" "$REPO/$1"; }

# 配置先 と stubの内容（空は撤去する旧stub）
TARGETS=(
  "$HOME/.vimrc"
  "$HOME/.vimrc_local"
  "$HOME/.config/nvim/init.vim"
  "$HOME/.config/powershell/profile.ps1"
  "$HOME/.config/powershell/Microsoft.PowerShell_profile.ps1"
  "$HOME/.tmux.conf"
  "$HOME/.bash_profile"
  "$HOME/.bashrc"
  "$HOME/.inputrc"
)
CONTENTS=(
  "$(vim_stub .vimrc)"
  "$(vim_stub mac/.vimrc_local)"
  "$(vim_stub .vimrc)"
  "$(pwsh_stub profile.ps1)"
  ""
  "$(tmux_stub .tmux.conf)"
  "$(sh_stub mac/.bash_profile)"
  "$(sh_stub mac/.bashrc)"
  "$(rl_stub mac/.inputrc)"
)

# git のグローバル設定
GIT_KEYS=(core.attributesFile core.autocrlf)
GIT_VALUES=("$REPO/.config/git/attributes" false)

# リポジトリ内を指すパスか（ファイル自体は存在しなくてよい）
in_repo() {
  local d
  d="$(cd "$(dirname "$1")" 2>/dev/null && pwd -P)" || return 1
  case "$d/$(basename "$1")/" in "$REPO"/*) return 0 ;; esac
  return 1
}

# skip: 同一・撤去済み / install: なし / update: 古いstub / link: リポジトリへのリンク（旧方式）
# remove: 撤去する旧stub / conflict: 管理外
action() {
  local t="$1" c="$2" l
  in_repo "$(dirname "$t")/." && { echo conflict; return; }
  if [ -L "$t" ]; then
    l="$(readlink "$t")"
    case "$l" in /*) ;; *) l="$(dirname "$t")/$l" ;; esac
    if in_repo "$l"; then [ -z "$c" ] && echo remove || echo link; else echo conflict; fi
  elif [ ! -e "$t" ]; then
    [ -z "$c" ] && echo skip || echo install
  elif [ -d "$t" ] || ! grep -qF "$MARKER" "$t"; then
    echo conflict
  elif [ -z "$c" ]; then
    echo remove
  elif cmp -s <(printf '%s\n' "$c") "$t"; then
    echo skip
  else
    echo update
  fi
}

# 色付きで1行表示
show() {
  local color=32
  case "$1" in skip) color=90 ;; conflict) color=31 ;; esac
  printf '  \033[%sm%-8s %s\033[0m\n' "$color" "$1" "$2"
}

echo "repo: $REPO"
ACTIONS=() GIT_ACTIONS=() conflict=""
for i in "${!TARGETS[@]}"; do
  ACTIONS[i]="$(action "${TARGETS[i]}" "${CONTENTS[i]}")"
  show "${ACTIONS[i]}" "~${TARGETS[i]#"$HOME"}"
  [ "${ACTIONS[i]}" = conflict ] && conflict=1
done
for i in "${!GIT_KEYS[@]}"; do
  if [ "$(git config --global --get "${GIT_KEYS[i]}" || true)" = "${GIT_VALUES[i]}" ]; then
    GIT_ACTIONS[i]=skip
  else
    GIT_ACTIONS[i]=set
  fi
  show "${GIT_ACTIONS[i]}" "git ${GIT_KEYS[i]}"
done
if [ -n "$conflict" ]; then
  printf '\033[31mconflict のファイルを退避・削除してから再実行してください（変更なし）\033[0m\n'
  exit 1
fi
[ -n "$DRY_RUN" ] && exit 0

for i in "${!TARGETS[@]}"; do
  t="${TARGETS[i]}"
  case "${ACTIONS[i]}" in
    skip) continue ;;
    link|remove) rm -f "$t" ;;
  esac
  [ "${ACTIONS[i]}" = remove ] && continue
  mkdir -p "$(dirname "$t")"
  printf '%s\n' "${CONTENTS[i]}" > "$t"
done
for i in "${!GIT_KEYS[@]}"; do
  [ "${GIT_ACTIONS[i]}" = set ] && git config --global "${GIT_KEYS[i]}" "${GIT_VALUES[i]}"
done
exit 0
